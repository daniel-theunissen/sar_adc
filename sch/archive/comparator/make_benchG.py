"""Writes the bench G netlist for the Fig. 15 comparator (phi1 / phi2 clocking).

usage:  python3 make_benchG.py [--eval 70] [--gap 2] [--skew 0.3] [--corner tt] [--temp 27]
                               [--plan full|short] [--tag NAME] [--out FILE]
        python3 make_benchG.py --sweep-gap 0.5,1,2,3,5,8      (one short-plan netlist per gap, plus run_gap_sweep.sh)

Edit the constants below for the defaults; the analysis notebook (bench_g_analysis.ipynb) has the same numbers in its
CONFIG cell, but it finds the actual clock edges in the data, so command-line overrides need no notebook change."""
import sys, argparse

VDD = 1.8
T_BIT = 100.0        # ns, bit period
T_STEP = 2.0         # ns after the start of a cycle: the inputs change (the DAC step arrives at the comparator input)
T_EVAL = 70.0        # ns: phi1 rises, T9 opens, the PMOS latch starts regenerating (analog settling done: 53 ns + digital + margin)
GAP = 2.0            # ns: phi2 falls GAP after phi1 rises, T7/T8 join the NMOS latch (start of the sweep; my estimate is 1..3 ns)
T_CONN = T_EVAL + GAP
T_SKEW = 0.3         # ns: at the end of the cycle phi2 rises (NMOS latch reset) at T_BIT and phi1 falls (T9 on) this much later
VCM0 = 0.949         # V, nominal input common mode (bench E mean)
R_SRC = 35e3         # ohm, source resistance seen by each comparator input (the clamp cell / ladder node)
C_IN = 95e-15        # F, extra capacitance at each input node (node total ~ 100 fF with the comparator's own input capacitance)
C_OUT = 10e-15       # F, load on each output
LIB = '/foss/pdks/sky130A/libs.tech/combined/sky130.lib.spice'

def plan(kind='full'):
    """List of (group, common mode, differential) per bit cycle. 'short' is for the gap sweep (A and a coarser ramp C)."""
    cyc = []
    for mag in (0.1, 0.2, 0.5, 1, 2, 5, 10, 20, 50, 100):        # group A: delay vs overdrive, both signs
        for s in (+1, -1):
            cyc.append(('A', VCM0, s * mag * 1e-3))
    if kind == 'full':
        for vcm in (0.6, 0.7, 0.8, 0.9, 0.949, 1.0, 1.1, 1.2, 1.3):     # group B: input common mode
            for d in (5, -5, 1, -1):
                cyc.append(('B', vcm, d * 1e-3))
        ramp = [-12 + 0.25 * i for i in range(97)]                 # group C: offset and hysteresis
    else:
        ramp = [-8 + 0.5 * i for i in range(33)]
    for d in ramp:
        cyc.append(('C+', VCM0, d * 1e-3))
    for d in ramp[::-1]:
        cyc.append(('C-', VCM0, d * 1e-3))
    return cyc

def pwl(kind, cyc):
    pts = []
    for k, (g, vcm, vd) in enumerate(cyc):
        v = vcm + (0.5 if kind == 'p' else -0.5) * vd
        if k == 0:
            pts.append((0.0, v))
        else:
            t = k * T_BIT + T_STEP
            pts.append((t, pts[-1][1]))
            pts.append((t + 0.1, v))
    pts.append((len(cyc) * T_BIT, pts[-1][1]))
    lines, cur = [], ''
    for t, v in pts:
        s = f' {t:.1f}n {v:.7f}'
        if len(cur) + len(s) > 100:
            lines.append(cur); cur = ''
        cur += s
    lines.append(cur)
    return '\n+'.join(['pwl(' + lines[0]] + lines[1:]) + ')'

def netlist(t_eval, gap, skew, corner, temp, plan_kind, csv_name):
    cyc = plan(plan_kind)
    t_total = len(cyc) * T_BIT
    t_conn = t_eval + gap
    n = lambda x: f'{x:g}n'
    return f'''** Bench G: the Fig. 15 comparator on its own, driven through the node impedance of the summing stage.
** Needs comparator.spice (or your own subcircuit with the same pins) in the same folder. {len(cyc)} cycles of {T_BIT:g} ns ({plan_kind} plan), corner {corner}, {temp:g} C.
** Cycle k starts at k*{T_BIT:g} ns: reset (phi1 LOW = T9 on, phi2 HIGH = NMOS latch off and Q = Qb = 0), the inputs step at +{T_STEP:g} ns,
**   phi1 rises at +{t_eval:g} ns (release, PMOS latch regenerates), phi2 falls at +{t_conn:g} ns (gap {gap:g} ns, NMOS latch connected),
**   at the end of the cycle phi2 rises at {T_BIT:g} ns and phi1 falls {skew:g} ns later (reset again, the decision is lost on Q/Qb).
** Groups: A = overdrive 0.1..100 mV both signs; B = common mode 0.6..1.3 V at +/-5 mV and +/-1 mV (full plan only); C = offset ramp, up then down.
** An SR latch (two NOR gates) on Q/Qb holds the decision through the reset: outputs vlat / vlatb.
** Generated by make_benchG.py.
.include comparator.spice

.param rsrc={R_SRC:g} cin={C_IN:g} cout={C_OUT:g}
Vdd VDD 0 {VDD}
* clocks. phi1: LOW = reset. phi2: HIGH = reset (NMOS latch off, connect switches off); LOW = connected
Vphi1 phi1 0 pulse(0 {VDD} {n(t_eval)} 0.1n 0.1n {n(T_BIT + skew - t_eval - 0.1)} {n(T_BIT)})
Vphi2 phi2 0 pulse({VDD} 0 {n(t_conn)} 0.1n 0.1n {n(T_BIT - t_conn - 0.1)} {n(T_BIT)})
* ideal differential sources, then the node impedance of the summing stage
Vsp sp 0 {pwl('p', cyc)}
Vsn sn 0 {pwl('n', cyc)}
Rsp sp inp {{rsrc}}
Rsn sn inn {{rsrc}}
Cinp inp 0 {{cin}}
Cinn inn 0 {{cin}}
Xc VDD 0 inp inn phi1 phi2 outp outn comparator
Cop outp 0 {{cout}}
Con outn 0 {{cout}}

* SR latch on the (return-to-zero) outputs: vlat = decision, held while Q and Qb are both 0
.subckt cmp_nor2 a b y VDD GND
XP1 n1 a VDD VDD sky130_fd_pr__pfet_01v8 L=0.15 W=2
XP2 y b n1 VDD sky130_fd_pr__pfet_01v8 L=0.15 W=2
XN1 y a GND GND sky130_fd_pr__nfet_01v8 L=0.15 W=1
XN2 y b GND GND sky130_fd_pr__nfet_01v8 L=0.15 W=1
.ends cmp_nor2
Xs1 outn vlatb vlat VDD 0 cmp_nor2
Xs2 outp vlat vlatb VDD 0 cmp_nor2
.nodeset v(vlat)=0 v(vlatb)={VDD}

.lib {LIB} {corner}
.temp {temp:g}
.options reltol=1e-5
.save all
.save i(vdd)

.control
  set wr_singlescale
  tran 0.1n {t_total:g}n
  let vsp_ = v(sp)
  let vsn_ = v(sn)
  let vinp = v(inp)
  let vinn = v(inn)
  let voutp = v(outp)
  let voutn = v(outn)
  let idd = -i(Vdd)
  let vp1 = v(phi1)
  let vp2 = v(phi2)
  let vl = v(vlat)
  let vlb = v(vlatb)
  let vna = v(xc.a)
  let vnb = v(xc.b)
  let vtl = v(xc.tail)
  wrdata {csv_name} vsp_ vsn_ vinp vinn voutp voutn idd vp1 vp2 vl vlb vna vnb vtl
.endc

.end
'''

def gtag(g):
    return f'{g:g}'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--eval', type=float, default=T_EVAL, help='ns, phi1 rises')
    ap.add_argument('--gap', type=float, default=GAP, help='ns, phi2 falls this long after phi1 rises')
    ap.add_argument('--skew', type=float, default=T_SKEW, help='ns, phi1 returns to reset this long after phi2')
    ap.add_argument('--corner', default='tt')
    ap.add_argument('--temp', type=float, default=27.0)
    ap.add_argument('--plan', default='full', choices=['full', 'short'])
    ap.add_argument('--tag', default='', help='suffix for the netlist and csv names, e.g. ss_125')
    ap.add_argument('--out', default=None)
    ap.add_argument('--sweep-gap', default=None, help='comma list of gaps in ns: writes short-plan netlists tran_g_gap<g>.csv and run_gap_sweep.sh')
    a = ap.parse_args()
    if a.sweep_gap:
        gaps = [float(x) for x in a.sweep_gap.split(',')]
        sh = ['#!/bin/sh', '# runs the gap sweep; each run writes tran_g_gap<gap>.csv (short plan, about 90 cycles)']
        for g in gaps:
            name = f'comparator_benchG_gap{gtag(g)}.spice'
            open(name, 'w').write(netlist(a.eval, g, a.skew, a.corner, a.temp, 'short', f'tran_g_gap{gtag(g)}.csv'))
            sh.append(f'ngspice -b {name}')
            print('wrote', name)
        open('run_gap_sweep.sh', 'w').write('\n'.join(sh) + '\n')
        print('wrote run_gap_sweep.sh')
        return
    csv = f'tran_g{("_" + a.tag) if a.tag else ""}.csv'
    out = a.out or f'comparator_benchG{("_" + a.tag) if a.tag else ""}.spice'
    open(out, 'w').write(netlist(a.eval, a.gap, a.skew, a.corner, a.temp, a.plan, csv))
    print('wrote', out, '->', csv, f'({len(plan(a.plan))} cycles)')

if __name__ == '__main__':
    main()
